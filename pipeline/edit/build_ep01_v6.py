"""Сборка EP01 v6 — тринадцать шотов, 1080x1920, 30 fps.

Два правила, выведенных из брака 31.08.2026:

1. Материал почти не движется. Замер по исходным окнам: девять шотов из
   тринадцати дают меньше 0,9 по кадровой разнице, то есть это фотографии
   с зерном. На вертикали неподвижный план дольше секунды читается как
   зависшее видео.

2. Статический кроп этого не лечит. Он меняет крупность и не добавляет
   движения. Нужен наезд, растянутый на всю длину шота: 6-12 процентов за
   два секунды не читается как движение камеры, но не даёт кадру замереть.

SH010 наезда не получает: по канону камера в нём заперта и «не помогает
зрителю смотреть». Его событие — гаснущие буквы на табличке, они ставятся
в композе.
"""
import subprocess, sys

DUMP = "incoming/VIDEO_DUMP/%s.mp4"
W, H, FPS = 1080, 1920, 30
OUT = sys.argv[1] if len(sys.argv) > 1 else "out.mp4"

# шот, файл, вход, длительность, наезд за шот (доля кадра), статический кроп
CUT = [
    ("SH001", "EP01_SH001_v1", 1.83, 1.8, 0.17, 0.14),
    ("SH002", "EP01_SH002_v2", 3.67, 2.0, 0.00, 0.00),
    ("SH003", "EP01_SH003_v3", 2.60, 2.0, 0.16, 0.00),
    ("SH004", "EP01_SH004_v2", 0.60, 2.2, 0.00, 0.00),
    ("SH005", "EP01_SH005_v1", 3.20, 2.2, 0.15, 0.26),
    ("SH006", "EP01_SH006_v1", 0.30, 1.8, 0.00, 0.00),
    ("SH007", "EP01_SH007_v1", 2.20, 1.2, 0.07, 0.00),
    ("SH008", "EP01_SH008_v1", 2.00, 2.0, 0.08, 0.00),
    ("SH010", "EP01_SH010_v1", 0.00, 2.6, 0.00, 0.00),
    ("SH011", "EP01_SH011_v2", 1.40, 1.8, 0.00, 0.00),
    ("SH012", "EP01_SH012_v1", 3.80, 2.0, 0.08, 0.00),
    ("SH013", "EP01_SH013_v1", 1.90, 1.0, 0.06, 0.00),
    ("SH014", "EP01_SH014_v1", 1.20, 2.45, 0.11, 0.18),
]

parts, filt = [], []
for i, (shot, f, tin, dur, push, crop) in enumerate(CUT):
    parts += ["-ss", f"{tin}", "-t", f"{dur}", "-i", DUMP % f]
    v = f"[{i}:v]"
    # приводим к 30 fps и к двойному разрешению: наезд по целым пикселям
    # на удвоенном кадре не даёт ступенек
    filt.append(f"{v}fps={FPS},scale={W*2}:{H*2}:force_original_aspect_ratio=increase,"
                f"crop={W*2}:{H*2}[b{i}]")
    v = f"[b{i}]"
    if crop > 0:                       # неподвижная врезка: меняет крупность
        z = 1.0 - crop
        filt.append(f"{v}crop=iw*{z}:ih*{z}:(iw-iw*{z})/2:(ih-ih*{z})/2[c{i}]")
        v = f"[c{i}]"
    if push > 0:                       # наезд на всю длину шота
        nf = max(2, round(dur * FPS))
        filt.append(f"{v}zoompan=z='1+{push}*on/{nf-1}':d=1:"
                    f"x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)':"
                    f"s={W}x{H}:fps={FPS}[z{i}]")
        v = f"[z{i}]"
    else:
        filt.append(f"{v}scale={W}:{H}[z{i}]")
        v = f"[z{i}]"
    filt.append(f"{v}setsar=1[v{i}]")

filt.append("".join(f"[v{i}]" for i in range(len(CUT))) +
            f"concat=n={len(CUT)}:v=1:a=0[out]")

subprocess.run(["ffmpeg", "-y", "-hide_banner", "-loglevel", "error", *parts,
                "-filter_complex", ";".join(filt), "-map", "[out]",
                "-c:v", "libx264", "-crf", "17", "-preset", "slow",
                "-pix_fmt", "yuv420p", "-an", "-movflags", "+faststart", OUT],
               check=True)

t = 0.0
print(f"{'шот':7s}{'вход':>7s}{'длит':>6s}{'наезд':>7s}{'склейка':>9s}")
for shot, f, tin, dur, push, crop in CUT:
    t += dur
    print(f"{shot:7s}{tin:7.2f}{dur:6.2f}{push*100:6.0f}%{t:9.2f}")
print(f"итого {t:.2f} с")
